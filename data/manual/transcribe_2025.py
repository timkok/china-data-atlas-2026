def _write_panel(path: Path, indicator_id: str, years: list[int], panel: dict, source_url: str, source_table: str, scope_note: str) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["indicator_id", "region_code", "year", "value", "yearbook_year", "source_url", "source_table", "scope_note"],
        )
        writer.writeheader()
        for code, _name in PROVINCES:
            for offset, year in enumerate(years):
                writer.writerow(
                    {
                        "indicator_id": indicator_id,
                        "region_code": code,
                        "year": year,
                        "value": panel[code][offset],
                        "yearbook_year": 2025,
                        "source_url": source_url,
                        "source_table": source_table,
                        "scope_note": scope_note,
                    }
                )


